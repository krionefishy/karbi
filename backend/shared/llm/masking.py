"""Маскирование персональных данных перед отправкой текста в нейросеть.

Это наш собственный слой поверх правил защиты на стороне провайдера: он ловит
то, что провайдер пропускает (имена в тексте, номера карт и заказов), и не
зависит от настроек в его кабинете.
"""

import re

_EMAIL = re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+")
_UUID = re.compile(r"\b[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}\b")
_URL = re.compile(r"https?://\S+")
# Телефоны и номера карт: длинные цепочки цифр с пробелами, скобками и дефисами.
_LONG_NUMBER = re.compile(r"(?<![\w])\+?\d[\d\s().-]{7,}\d(?![\w])")


def mask_pii(text: str) -> str:
    """Заменяет почту, ссылки, идентификаторы и длинные номера на заглушки. Смысл текста остаётся."""
    masked = _EMAIL.sub("<EMAIL>", text)
    masked = _UUID.sub("<ID>", masked)
    masked = _URL.sub("<URL>", masked)
    return _LONG_NUMBER.sub("<NUM>", masked)
